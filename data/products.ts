// Helper functions for easy filtering
export const NEW_ARRIVALS = PRODUCTS.filter((p) => p.isNewArrival);
export const BEST_SELLERS = PRODUCTS.filter((p) => p.isBestSeller);
export const FEATURED_FASHION = PRODUCTS.filter((p) => p.category === "Women's Clothing" || p.category === 'Handbags');
export const BEAUTY_COLLECTION = PRODUCTS.filter((p) => p.category === 'Makeup' || p.category === 'Skincare');
export const JEWELLERY_COLLECTION = PRODUCTS.filter((p) => p.category === 'Jewellery' || p.category === 'Watches');

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getProductsByCategory(categoryName: string): Product[] {
  return PRODUCTS.filter((p) => p.category.toLowerCase() === categoryName.toLowerCase());
}

export function getRelatedProducts(currentProductId: string, limit: number = 4): Product[] {
  const current = getProductById(currentProductId);
  if (!current) return PRODUCTS.slice(0, limit);
  return PRODUCTS.filter((p) => p.id !== currentProductId && p.category === current.category).concat(
    PRODUCTS.filter((p) => p.id !== currentProductId && p.category !== current.category)
  ).slice(0, limit);
}

